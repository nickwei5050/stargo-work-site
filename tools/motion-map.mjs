/**
 * One-off generator for js/stargo-motion-map.js: the dotted world map the
 * Growth OS motion scene draws (tools/motion-scenes.mjs, js/stargo-motion.js).
 *
 *   npm pack world-atlas@2.0.2 && tar xzf world-atlas-2.0.2.tgz
 *   node tools/motion-map.mjs package/land-110m.json
 *
 * Natural Earth land (public domain) via world-atlas (ISC). The output is
 * committed, so the site build never needs the network for it. Equirectangular,
 * longitude -180…180, latitude 78…-58, a dot every STEP degrees on alternate
 * rows offset by half a step; each dot is written as x,y in 0…1000 / 0…(h).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { SITE } from './paths.mjs';

const STEP = 2.1;
const LAT_TOP = 78, LAT_BOTTOM = -58;
const topo = JSON.parse(readFileSync(process.argv[2], 'utf8'));
const { scale, translate } = topo.transform;

// decode delta-encoded arcs to lon/lat
const arcs = topo.arcs.map((arc) => {
  let x = 0, y = 0;
  return arc.map(([dx, dy]) => { x += dx; y += dy; return [x * scale[0] + translate[0], y * scale[1] + translate[1]]; });
});
const ring = (ids) => ids.flatMap((i, k) => {
  const a = i < 0 ? arcs[~i].slice().reverse() : arcs[i];
  return k ? a.slice(1) : a;
});
const polygons = [];
for (const g of topo.objects.land.geometries) {
  const polys = g.type === 'Polygon' ? [g.arcs] : g.arcs;
  for (const p of polys) polygons.push(p.map(ring));
}
function inRing(x, y, r) {
  let inside = false;
  for (let i = 0, j = r.length - 1; i < r.length; j = i++) {
    const [xi, yi] = r[i], [xj, yj] = r[j];
    if ((yi > y) !== (yj > y) && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}
const onLand = (x, y) => polygons.some((p) => inRing(x, y, p[0]) && !p.slice(1).some((h) => inRing(x, y, h)));

const W = 1000, H = Math.round((W * (LAT_TOP - LAT_BOTTOM)) / 360);
const out = [];
let row = 0;
for (let lat = LAT_TOP - STEP / 2; lat > LAT_BOTTOM; lat -= STEP, row++) {
  for (let lon = -180 + (row % 2 ? STEP : STEP / 2); lon < 180; lon += STEP) {
    if (!onLand(lon, lat)) continue;
    out.push(Math.round(((lon + 180) / 360) * W), Math.round(((LAT_TOP - lat) / (LAT_TOP - LAT_BOTTOM)) * H));
  }
}
const js = `/* Dotted world map for the Growth OS motion scene. Generated by tools/motion-map.mjs
   from Natural Earth land (public domain) via world-atlas 2.0.2 (ISC). Do not edit. */
window.STARGO_MAP = { w: ${W}, h: ${H}, top: ${LAT_TOP}, bottom: ${LAT_BOTTOM}, dots: [${out.join(',')}] };
`;
writeFileSync(`${SITE}/js/stargo-motion-map.js`, js);
console.log(`${out.length / 2} dots, ${W}x${H}, ${js.length} bytes`);
