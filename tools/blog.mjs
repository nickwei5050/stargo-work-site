const cta = (zh, en) => B(`<p class="sgp-cta">${zh}</p>`, `<p class="sgp-cta">${en}</p>`);
const Q = (qzh, qen, azh, aen) => ({ q: B(qzh, qen), a: B(azh, aen) });

/** The highlighted list printed right after an article's first paragraph. */
export function renderTakeaways(post, lang) {
  if (!post.takeaways?.length) return '';
  return `<aside class="sgp-takeaways" aria-labelledby="sgp-takeaways-title"><p class="sgp-takeaways-title" id="sgp-takeaways-title">${esc(BLOG_UI.takeaways[lang])}</p><ul>${post.takeaways.map((x) => `<li>${esc(x[lang])}</li>`).join('')}</ul></aside>`;
}

/** The visible FAQ at the end of an article: the same words as faqEntities(). */
export function renderFaq(post, lang) {
  if (!post.faq?.length) return '';
  return `<section class="sgp-faq" aria-labelledby="sgp-faq-title"><h3 id="sgp-faq-title">${esc(BLOG_UI.faq[lang])}</h3>`
    + post.faq.map((f) => `<div class="sgp-faq-item"><h4>${inline(f.q[lang])}</h4><p>${esc(f.a[lang])}</p></div>`).join('')
    + '</section>';
}

/** schema.org Question entities for the FAQPage node; plain text, identical to renderFaq()'s text. */
export const faqEntities = (post, lang) => (post.faq ?? []).map((f) => ({ '@type': 'Question', name: bare(f.q[lang]), acceptedAnswer: { '@type': 'Answer', text: f.a[lang] } }));

/** The article body as printed: lead paragraph, takeaways, the rest, FAQ. */
export function renderBody(post, lang) {
  const text = phraseHeadings(post.body[lang].trim());
  const body = lang === 'zh' ? ctaWords(text) : text;
  const cut = body.indexOf('</p>');
  if (!body.startsWith('<p>') || cut < 0) throw new Error(`blog ${post.slug}: the body must open with its answer paragraph`);
  return body.slice(0, cut + 4) + renderTakeaways(post, lang) + body.slice(cut + 4) + renderFaq(post, lang);
}

const plain = (html) => html.replace(/<[^>]+>/g, ' ').replace(/&[a-z]+;|&#\d+;/g, ' ');
/**
 * schema.org wordCount of the printed article (body, takeaways and FAQ).
 * English: words. Chinese: characters — every Han character counts one, and
 * each Latin or numeric run (Growth OS, AI, 288) counts one, as a Chinese
 * word count does. Punctuation and spaces are not counted.
 */
export function wordCount(post, lang) {
  const text = plain(renderBody(post, lang));
  if (lang === 'en') return (text.match(/[A-Za-z0-9][A-Za-z0-9’'.&-]*/g) ?? []).length;
  return (text.match(/\p{Script=Han}/gu) ?? []).length + (text.match(/[A-Za-z0-9][A-Za-z0-9.&-]*/g) ?? []).length;
}

